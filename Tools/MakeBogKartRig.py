# Writes Content/KartData/Visuals/BogKart.json from Art/BogKart/BogKartLayout.json (written by Tools/SplitBogKart.py).
#   python -I Tools/MakeBogKartRig.py
import json, os
ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
lay = json.load(open(os.path.join(ROOT, 'Art', 'BogKart', 'BogKartLayout.json')))
P = '/Game/KartVisuals/BogKart/SM_Bog_%s.SM_Bog_%s'
FIT = {'FL': 0.128, 'FR': 0.128, 'RL': 0.131, 'RR': 0.131}   # model tyre radii (m): wheels scale to the config radius
G = 0.1397   # model rear-axle centre placed at the Rotax rear-wheel centre height (kart frame z = height above ground)
up = lambda v: [v[0], v[1], v[2] + G]
parts = []
for pt in lay['parts']:
    a, c, part = pt['asset'], pt['class'], pt['part']
    e = {"mesh": P % (a, a), "material": c}
    if part == 'Body':
        e.update({"attach": "chassis", "location": [0.0, 0.0, G]})
        if a == 'Body_skinrear':
            e["panel"] = "bumper"   # rear bumper: pushed in by a rear impact (damage)
    elif part == 'Nose':
        # CIK front fairing (Tools/SplitNose.py): pushed back on the model when the kit releases (damage)
        e.update({"attach": "chassis", "location": [0.0, 0.0, G], "panel": "nose"})
    elif part in ('SidepodL', 'SidepodR'):
        # sidepods (Tools/SplitSidepods.py): knocked loose by a side impact (damage)
        e.update({"attach": "chassis", "location": [0.0, 0.0, G], "panel": "sidepod" + part[-1]})
    elif part.startswith('Wheel'):
        w = part[5:]
        e.update({"attach": "wheel" + w, "kartAligned": True, "fitRadius": FIT[w]})
    elif part == 'Steer':
        e.update({"attach": "steeringWheel", "kartAligned": True})
    elif part.startswith('Spindle'):
        e.update({"attach": "upright" + ("FL" if part.endswith('L') else "FR"), "kartAligned": True})
    elif part == 'RearSpin':
        e.update({"attach": "rearAxle", "kartAligned": True})
    elif part.startswith('TieRod'):
        s = part[-1]
        t, kp = lay['tieRods'][s], lay['kingpins'][s]
        e.update({"attach": "tieRod" + s, "location": up(t['outer']), "inner": up(t['inner']),
                  "outerFromKingpin": [t['outer'][i] - kp[i] for i in range(3)]})
    parts.append(e)
# Imported driver (Tools/DriverSuit): suit parts posed in the kart frame at the game's rest pose + the Arai helmet on the
# head pivot. The procedural gloves stay (they grip the rim); "driverBody" / "helmetShell" hide the procedural rest.
DRV = os.path.join(ROOT, 'Art', 'Driver', 'driver_layout.json')
hide_driver = []
if os.path.exists(DRV):
    dl = json.load(open(DRV))
    rigj = json.load(open(os.path.join(ROOT, 'Build', 'Windows', 'KRPKNKOFF', 'Saved', 'DriverRig.json')))
    ATT = {'Body': 'driverBody', 'Boots': 'driverBody', 'Torso': 'torso', 'UpperArmL': 'upperArmL', 'UpperArmR': 'upperArmR',
           'ForearmL': 'forearmL', 'ForearmR': 'forearmR', 'Neck': 'torso'}
    D = '/Game/KartVisuals/Driver/SM_%s.SM_%s'
    for pt in dl['parts']:
        parts.append({"mesh": D % (pt['asset'], pt['asset']), "attach": ATT[pt['part']], "location": [0.0, 0.0, 0.0], "material": pt['class']})
    # helmet lifted along the spine (helmetLift) (visual only; the cockpit eye is unchanged) so a little balaclava neck shows
    # above the suit collar instead of the shell resting on it
    sp = [rigj['neck'][i] - rigj['pelvis'][i] for i in range(3)]; spn = sum(c * c for c in sp) ** 0.5
    lift = dl.get('helmetLift', 0.025)   # set in make_driver.py (HELMET_LIFT)
    helm = [rigj['helmetCentre'][i] + lift * sp[i] / spn for i in range(3)]
    parts.append({"mesh": D % ('Helmet_Arai', 'Helmet_Arai'), "attach": "helmet", "location": helm})
    hide_driver = ["driverBody", "helmetShell"]
rig = {"hide": ["frame", "bodywork", "steeringWheel", "wheels"] + hide_driver,
       "steeringColumn": {"hub": up(lay['steerHub']), "axis": lay['columnAxis']},
       "kingpins": {s: up(v) for s, v in lay['kingpins'].items()},
       "parts": parts}
hdr = '''// "Bog kart": the user's Blender kitbash (kips bog bog kart.fbx). Generated by Tools/MakeBogKartRig.py from the layout
// measured by Tools/SplitBogKart.py; meshes imported by Tools/ImportBogKart.py. Body pivot = model rear-axle centre at
// the Rotax rear-wheel centre height. Wheels fitted to the configured tyre radius. Spindles pivot at the model's
// chassis-fixed kingpins (a track change slides the wheel along the stub axle), rear hub sleeves + disc spin with the
// axle, tie rods are solved each frame between the column arm and the spindle arm. skin* / sw* = R2S livery (humans).
'''
open(os.path.join(ROOT, 'Content', 'KartData', 'Visuals', 'BogKart.json'), 'w').write(hdr + json.dumps(rig, indent=1))
print('rig parts', len(parts), 'kingpins', rig['kingpins'], 'column', rig['steeringColumn'])
