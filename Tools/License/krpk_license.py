"""KRPKNKOFF tester license keys.

  python Tools/License/krpk_license.py init                    create YOUR signing key pair (once) and put the public
                                                               key into the game source (rebuild the game afterwards)
  python Tools/License/krpk_license.py issue --name "Sam" --machine ABCD-EFGH-JKLM-NPQR [--days 30]
                                                               make a key for one tester's PC (they see the machine
                                                               code on the game's activation screen)
  python Tools/License/krpk_license.py verify KEY [--machine CODE]   check / decode a key
  python Tools/License/krpk_license.py list                    the ledger of issued keys

Revoking (the game downloads a signed revocation list at startup; testers must be online at least every 7 days):
  python Tools/License/krpk_license.py revocation-setup --github     one-time: create a secret GitHub Gist for the list
                                                                     (asks for a GitHub token with the "gist" scope)
  python Tools/License/krpk_license.py revocation-setup --url URL    or: you host krpk_revoked.txt yourself at URL
  python Tools/License/krpk_license.py revoke --key-id ID | --machine CODE | --name NAME   (then it publishes)
  python Tools/License/krpk_license.py unrevoke --key-id ID | --machine CODE
  python Tools/License/krpk_license.py revoked                 show the current list
  python Tools/License/krpk_license.py revocation-token        replace an expired GitHub token (same Gist, no rebuild)
After revocation-setup the game must be rebuilt / repackaged once (the URL is compiled in).

The PRIVATE key lives OUTSIDE the project: %USERPROFILE%\\KRPKNKOFF_Signing\\license_private_key.pem (override with
KRPK_SIGNING_DIR). Anyone with that file can make keys: back it up somewhere safe (USB stick / password manager),
never put it in the game folder, a zip, a repository or a chat. Losing it means re-keying every tester.
Every issued key is appended to issued_keys.csv next to it (who, which PC, when, until when).

Key format (must match Source/KartSimCore/Private/KartSim/License.cpp):
  base64url(payload) "." base64url(RSASSA-PKCS1-v1_5 SHA-256 signature),  payload = KRPK1|name|machine|YYYYMMDD|YYYYMMDD|id
"""
import argparse, base64, csv, datetime, getpass, json, os, re, secrets, sys

from cryptography.hazmat.primitives import hashes, serialization
from cryptography.hazmat.primitives.asymmetric import padding, rsa

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
INC = os.path.join(ROOT, 'Source', 'KartSimCore', 'Private', 'KartSim', 'LicensePublicKey.inc')
SIGN_DIR = os.environ.get('KRPK_SIGNING_DIR', os.path.join(os.path.expanduser('~'), 'KRPKNKOFF_Signing'))
PRIV = os.path.join(SIGN_DIR, 'license_private_key.pem')
LEDGER = os.path.join(SIGN_DIR, 'issued_keys.csv')
REV_STATE = os.path.join(SIGN_DIR, 'revocation.json')     # revoked ids / machines, serial, publishing settings
REV_FILE = os.path.join(SIGN_DIR, 'krpk_revoked.txt')       # the signed list as published
REV_INC = os.path.join(ROOT, 'Source', 'KartSimCore', 'Private', 'KartSim', 'LicenseRevocation.inc')
REV_NAME = 'krpk_revoked.txt'
MACHINE_RE = re.compile(r'^[A-HJ-NP-Z2-9]{4}-[A-HJ-NP-Z2-9]{4}-[A-HJ-NP-Z2-9]{4}-[A-HJ-NP-Z2-9]{4}$')
NAME_RE = re.compile(r'^[A-Za-z0-9 _.\-]{1,32}$')


def b64u(b):
    return base64.urlsafe_b64encode(b).decode().rstrip('=')


def b64u_dec(s):
    return base64.urlsafe_b64decode(s + '=' * (-len(s) % 4))


def write_inc(pub, path=INC):
    n = pub.public_numbers().n
    hexn = '%0512x' % n
    with open(path, 'w', encoding='utf-8', newline='\n') as f:
        f.write('// Generated by Tools/License/krpk_license.py init: the PUBLIC half of the tester-license signing key (RSA-2048).\n')
        f.write('// Safe to ship. The private half stays in the developer\'s KRPKNKOFF_Signing folder.\n')
        f.write('static const char* KrpkLicenseModulusHex =\n')
        for i in range(0, len(hexn), 64):
            f.write('\t"%s"%s\n' % (hexn[i:i + 64], ';' if i + 64 >= len(hexn) else ''))
        f.write('static const uint32_t KrpkLicenseExponent = %du;\n' % pub.public_numbers().e)


def load_private():
    if not os.path.exists(PRIV):
        sys.exit('No signing key at %s - run "init" first (or set KRPK_SIGNING_DIR).' % PRIV)
    data = open(PRIV, 'rb').read()
    pw = None
    if b'ENCRYPTED' in data:
        pw = (os.environ.get('KRPK_SIGNING_PASSPHRASE') or getpass.getpass('Signing key passphrase: ')).encode()
    return serialization.load_pem_private_key(data, password=pw)


def make_key(priv, name, machine, days, today=None, key_id=None):
    today = today or datetime.date.today()
    exp = today + datetime.timedelta(days=days)
    key_id = key_id or secrets.token_hex(4)
    payload = 'KRPK1|%s|%s|%s|%s|%s' % (name, machine, today.strftime('%Y%m%d'), exp.strftime('%Y%m%d'), key_id)
    sig = priv.sign(payload.encode(), padding.PKCS1v15(), hashes.SHA256())
    return b64u(payload.encode()) + '.' + b64u(sig), payload, exp, key_id


def cmd_init(a):
    if os.path.exists(PRIV) and not a.force:
        sys.exit('A signing key already exists at %s. Keys issued with it stay valid only while the game keeps its public key;\n'
                 're-run with --force ONLY if you want to invalidate every issued key.' % PRIV)
    os.makedirs(SIGN_DIR, exist_ok=True)
    priv = rsa.generate_private_key(public_exponent=65537, key_size=2048)
    enc = serialization.NoEncryption()
    if a.passphrase:
        p1 = getpass.getpass('New passphrase for the signing key: ')
        if p1 != getpass.getpass('Repeat: '):
            sys.exit('Passphrases differ.')
        enc = serialization.BestAvailableEncryption(p1.encode())
    with open(PRIV, 'wb') as f:
        f.write(priv.private_bytes(serialization.Encoding.PEM, serialization.PrivateFormat.PKCS8, enc))
    write_inc(priv.public_key())
    print('Signing key created:  %s\nPublic key written to: %s\nBACK UP the private key file now. Then rebuild / repackage the game.' % (PRIV, INC))


def issue_key(priv, name, machine, days, note=''):
    """Validates, signs and records one key in the ledger. Raises ValueError on bad input. Shared with the Discord bot."""
    name = name.strip()
    machine = machine.strip().upper()
    if not NAME_RE.match(name):
        raise ValueError('Name: 1-32 characters, letters / digits / space / _ . - only (it is shown on screen).')
    if not MACHINE_RE.match(machine):
        raise ValueError('Machine code looks wrong (expected XXXX-XXXX-XXXX-XXXX from the activation screen): %s' % machine)
    if not 1 <= days <= 3650:
        raise ValueError('Days must be 1-3650.')
    key, payload, exp, key_id = make_key(priv, name, machine, days)
    os.makedirs(SIGN_DIR, exist_ok=True)
    new = not os.path.exists(LEDGER)
    with open(LEDGER, 'a', newline='', encoding='utf-8') as f:
        w = csv.writer(f)
        if new:
            w.writerow(['issued', 'expires', 'name', 'machine', 'key_id', 'note'])
        w.writerow([datetime.date.today().isoformat(), exp.isoformat(), name, machine, key_id, note or ''])
    return key, exp, key_id


def cmd_issue(a):
    try:
        key, exp, key_id = issue_key(load_private(), a.name, a.machine, a.days, a.note)
    except ValueError as e:
        sys.exit(str(e))
    machine = a.machine.strip().upper()
    print('License for %s (PC %s), valid until %s, key id %s:\n\n%s\n' % (a.name, machine, exp.isoformat(), key_id, key))
    if a.out:
        open(a.out, 'w', encoding='utf-8').write(key + '\n')
        print('Also written to', a.out)


def cmd_verify(a):
    priv = load_private()
    pub = priv.public_key()
    head, _, sig = a.key.strip().partition('.')
    payload = b64u_dec(head)
    try:
        pub.verify(b64u_dec(sig), payload, padding.PKCS1v15(), hashes.SHA256())
        ok = True
    except Exception:
        ok = False
    print('signature:', 'VALID' if ok else 'INVALID')
    print('payload:  ', payload.decode(errors='replace'))
    if a.machine:
        print('machine matches:', payload.decode().split('|')[2] == a.machine.strip().upper())


def cmd_list(a):
    if not os.path.exists(LEDGER):
        print('No keys issued yet.')
        return
    print(open(LEDGER, encoding='utf-8').read())


# ------------------------------------------------------------------------------------------------------- revocation
def rev_load():
    st = {'key_ids': [], 'machines': [], 'serial': 0, 'url': '', 'gist_id': '', 'github_token': ''}
    if os.path.exists(REV_STATE):
        st.update(json.load(open(REV_STATE, encoding='utf-8')))
    return st


def rev_save(st):
    os.makedirs(SIGN_DIR, exist_ok=True)
    tmp = REV_STATE + '.tmp'
    json.dump(st, open(tmp, 'w', encoding='utf-8'), indent=1)
    os.replace(tmp, REV_STATE)


def sign_revocation(priv, key_ids, machines, serial, today=None):
    today = today or datetime.date.today()
    payload = 'KRPKREV1|%s|%d|%s|%s' % (today.strftime('%Y%m%d'), serial, ','.join(sorted(set(key_ids))), ','.join(sorted(set(machines))))
    return b64u(payload.encode()) + '.' + b64u(priv.sign(payload.encode(), padding.PKCS1v15(), hashes.SHA256()))


def github_api(method, path, token, body=None):
    import urllib.request
    req = urllib.request.Request('https://api.github.com' + path, method=method, data=json.dumps(body).encode() if body is not None else None,
                                 headers={'Authorization': 'Bearer ' + token, 'Accept': 'application/vnd.github+json', 'User-Agent': 'krpk-license-tool',
                                          'X-GitHub-Api-Version': '2022-11-28'})
    with urllib.request.urlopen(req, timeout=20) as r:
        return json.loads(r.read().decode())


def publish_revocations(priv, st):
    """Signs the current list (new serial), writes krpk_revoked.txt and uploads it to the Gist if set up. Returns a status line."""
    st['serial'] = max(int(st.get('serial', 0)) + 1, int(datetime.datetime.now().timestamp()))
    text = sign_revocation(priv, st['key_ids'], st['machines'], st['serial'])
    rev_save(st)
    open(REV_FILE, 'w', encoding='utf-8', newline='\n').write(text + '\n')
    if st.get('gist_id') and st.get('github_token'):
        github_api('PATCH', '/gists/' + st['gist_id'], st['github_token'], {'files': {REV_NAME: {'content': text + '\n'}}})
        return 'Published to the GitHub Gist (testers pick it up within ~5 minutes, at their next game start).'
    if st.get('url'):
        return 'Written to %s - upload it to %s yourself.' % (REV_FILE, st['url'])
    return 'Written to %s, but revocation is not set up (run revocation-setup), so the game does not check it yet.' % REV_FILE


def key_ids_for_name(name):
    if not os.path.exists(LEDGER):
        return []
    rows = list(csv.DictReader(open(LEDGER, encoding='utf-8')))
    return [r['key_id'] for r in rows if r['name'].strip().lower() == name.strip().lower()]


def revoke(priv, key_ids=(), machines=(), names=(), undo=False):
    st = rev_load()
    ids = list(key_ids) + [k for n in names for k in key_ids_for_name(n)]
    machines = [m.strip().upper() for m in machines]
    if undo:
        st['key_ids'] = [k for k in st['key_ids'] if k not in ids]
        st['machines'] = [m for m in st['machines'] if m not in machines]
    else:
        st['key_ids'] = sorted(set(st['key_ids']) | set(ids))
        st['machines'] = sorted(set(st['machines']) | set(machines))
    return ids, machines, publish_revocations(priv, st)


def write_rev_inc(url):
    with open(REV_INC, 'w', encoding='utf-8', newline='\n') as f:
        f.write('// Written by Tools/License/krpk_license.py revocation-setup: where the game downloads the signed revocation list.\n')
        f.write('// Empty = revocation not set up (keys are then only limited by their expiry date).\n')
        f.write('static const char* KrpkRevocationUrl = "%s";\n' % url.replace('\\', '').replace('"', ''))


def cmd_revocation_setup(a):
    priv = load_private()
    st = rev_load()
    if a.github:
        token = os.environ.get('GITHUB_TOKEN') or getpass.getpass('GitHub token with the "gist" scope (hidden): ').strip()
        text = sign_revocation(priv, st['key_ids'], st['machines'], max(int(st.get('serial', 0)) + 1, 1))
        g = github_api('POST', '/gists', token, {'description': 'KRPKNKOFF license revocation list (signed)', 'public': False,
                                                 'files': {REV_NAME: {'content': text + '\n'}}})
        st.update(gist_id=g['id'], github_token=token, url='https://gist.githubusercontent.com/%s/%s/raw/%s' % (g['owner']['login'], g['id'], REV_NAME))
    elif a.url:
        st.update(url=a.url.strip(), gist_id='', github_token='')
    else:
        sys.exit('Use --github or --url URL.')
    rev_save(st)
    print(publish_revocations(priv, st))
    write_rev_inc(st['url'])
    print('Revocation list URL: %s\nWritten into %s - rebuild / repackage the game once so it checks this URL.' % (st['url'], REV_INC))


def cmd_revocation_token(a):
    """Replace the GitHub token (expired / revoked) without creating a new Gist: the game's URL stays the same."""
    st = rev_load()
    if not st.get('gist_id'):
        sys.exit('No GitHub Gist set up yet: run  revocation-setup --github  first.')
    token = os.environ.get('GITHUB_TOKEN') or getpass.getpass('New GitHub token with the "gist" scope (hidden): ').strip()
    github_api('GET', '/gists/' + st['gist_id'], token)  # fails here if the token cannot see the Gist
    st['github_token'] = token
    rev_save(st)
    print('Token replaced. ' + publish_revocations(load_private(), st))


def cmd_revoke(a, undo=False):
    if not (a.key_id or a.machine or getattr(a, 'name', None)):
        sys.exit('Give --key-id, --machine or --name.')
    ids, machines, status = revoke(load_private(), a.key_id or [], a.machine or [], getattr(a, 'name', None) or [], undo=undo)
    print('%s key ids %s, machines %s.\n%s' % ('Un-revoked' if undo else 'Revoked', ids or '-', machines or '-', status))


def cmd_revoked(a):
    st = rev_load()
    print('URL:      %s\nserial:   %s\nkey ids:  %s\nmachines: %s' % (st.get('url') or '(not set up)', st.get('serial'), ', '.join(st['key_ids']) or '-', ', '.join(st['machines']) or '-'))


def cmd_testvectors(a):
    # Cross-check for the C++ verifier (Tests/LicenseTestVectors.h): a throwaway key pair, NOT the game's.
    priv = rsa.generate_private_key(public_exponent=65537, key_size=2048)
    day = datetime.date(2026, 11, 20)
    good, _, _, _ = make_key(priv, 'Test Tester', 'ABCD-EFGH-JKLM-NPQR', 30, today=day, key_id='0badc0de')
    other = rsa.generate_private_key(public_exponent=65537, key_size=2048)
    forged, _, _, _ = make_key(other, 'Test Tester', 'ABCD-EFGH-JKLM-NPQR', 30, today=day, key_id='0badc0de')
    # Tampered: same signature, name changed in the payload.
    head, _, sig = good.partition('.')
    tampered = b64u(b64u_dec(head).replace(b'Test Tester', b'Evil Tester')) + '.' + sig
    hexn = '%0512x' % priv.public_key().public_numbers().n
    with open(a.out, 'w', encoding='utf-8', newline='\n') as f:
        f.write('// Generated by krpk_license.py testvectors (throwaway key pair, not the game\'s).\n#pragma once\n')
        f.write('static const char* LtModulusHex = "%s";\n' % hexn)
        f.write('static const char* LtGoodKey = "%s";\n' % good)
        f.write('static const char* LtForgedKey = "%s";\n' % forged)
        f.write('static const char* LtTamperedKey = "%s";\n' % tampered)
        f.write('static const char* LtRevokesGoodById = "%s";\n' % sign_revocation(priv, ['0badc0de', 'ffff0001'], [], 5, today=day))
        f.write('static const char* LtRevokesGoodByMachine = "%s";\n' % sign_revocation(priv, [], ['ABCD-EFGH-JKLM-NPQR'], 6, today=day))
        f.write('static const char* LtRevokesOthers = "%s";\n' % sign_revocation(priv, ['12345678'], ['ZZZZ-ZZZZ-ZZZZ-ZZZZ'], 7, today=day))
        f.write('static const char* LtRevokesForged = "%s";\n' % sign_revocation(other, ['12345678'], [], 8, today=day))
    print('wrote', a.out)


def main():
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    s = p.add_subparsers(dest='cmd', required=True)
    i = s.add_parser('init'); i.add_argument('--passphrase', action='store_true', help='protect the private key with a passphrase'); i.add_argument('--force', action='store_true')
    i.set_defaults(f=cmd_init)
    s1 = s.add_parser('issue'); s1.add_argument('--name', required=True); s1.add_argument('--machine', required=True)
    s1.add_argument('--days', type=int, default=30); s1.add_argument('--note'); s1.add_argument('--out'); s1.set_defaults(f=cmd_issue)
    v = s.add_parser('verify'); v.add_argument('key'); v.add_argument('--machine'); v.set_defaults(f=cmd_verify)
    l = s.add_parser('list'); l.set_defaults(f=cmd_list)
    t = s.add_parser('testvectors'); t.add_argument('out'); t.set_defaults(f=cmd_testvectors)
    rs = s.add_parser('revocation-setup'); rs.add_argument('--github', action='store_true'); rs.add_argument('--url'); rs.set_defaults(f=cmd_revocation_setup)
    rv = s.add_parser('revoke'); rv.add_argument('--key-id', action='append'); rv.add_argument('--machine', action='append'); rv.add_argument('--name', action='append')
    rv.set_defaults(f=cmd_revoke)
    ur = s.add_parser('unrevoke'); ur.add_argument('--key-id', action='append'); ur.add_argument('--machine', action='append')
    ur.set_defaults(f=lambda a: cmd_revoke(a, undo=True))
    rd = s.add_parser('revoked'); rd.set_defaults(f=cmd_revoked)
    rt = s.add_parser('revocation-token'); rt.set_defaults(f=cmd_revocation_token)
    a = p.parse_args()
    a.f(a)


if __name__ == '__main__':
    main()
